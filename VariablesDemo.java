package javastart;

public class VariablesDemo {

    public static void main(String[] args) {

        // byte: stores small whole numbers
        byte age = 24;

        // short: stores whole numbers larger than byte
        short year = 2026;

        // int: stores integer numbers
        int population = 100000;

        // long: stores very large whole numbers
        long distance = 9876543210L;

        // float: stores decimal numbers
        float height = 5.5f;

        // double: stores decimal numbers with higher precision
        double percentage = 73.88;

        // char: stores a single character
        char grade = 'A';

        // boolean: stores true or false
        boolean isJavaEasy = true;

        // String: stores a sequence of characters
        String name = "Mayur";

        // Print all variable values
        System.out.println("Name: " + name);
        System.out.println("Age: " + age);
        System.out.println("Year: " + year);
        System.out.println("Population: " + population);
        System.out.println("Distance: " + distance);
        System.out.println("Height: " + height);
        System.out.println("Percentage: " + percentage);
        System.out.println("Grade: " + grade);
        System.out.println("Is Java Easy: " + isJavaEasy);
    }
}